let currentLang = localStorage.getItem('admin-lang') || 'en';

function t(key) {
    const keys = key.split('.');
    let result = translations[currentLang];
    for (const k of keys) {
        if (result && typeof result === 'object') {
            result = result[k];
        } else {
            result = key;
            break;
        }
    }
    return result !== undefined ? result : key;
}

function setLanguage(lang) {
    if (translations[lang]) {
        currentLang = lang;
        localStorage.setItem('admin-lang', lang);
        document.documentElement.lang = lang;
        triggerLanguageChange();
    }
}

function getCurrentLanguage() {
    return currentLang;
}

let languageChangeListeners = [];

function onLanguageChange(callback) {
    languageChangeListeners.push(callback);
}

function triggerLanguageChange() {
    languageChangeListeners.forEach(callback => callback(currentLang));
}

function initI18n() {
    document.documentElement.lang = currentLang;
}

initI18n();
